#!/usr/bin/env python3
"""
Build yoai_aec3: a shared library with a plain C ABI over WebRTC's AEC3.

yoai_core cannot link AEC3 directly (WebRTC builds with clang-cl, Chromium's libc++, a
static CRT and C++20; yoai_core uses MSVC's STL, /MD and C++11), so everything C++ stays
inside this library and only plain C crosses the boundary. See aec3_bridge/yoai_aec3.h.

How it works: the sources in aec3_bridge/ are copied into <src>/yoai_aec3_bridge/, a
shared_library("yoai_aec3") target is appended to <src>/BUILD.gn, then gn + ninja build it.
Afterwards the copy and the BUILD.gn block are removed again, so the WebRTC checkout stays
clean (use --keep-patch to leave them, --unpatch to remove them by hand).

Outputs, in --output-dir (default: dist/yoai_aec3/<os>-<cpu> next to this script):
    Windows        yoai_aec3.dll   (+ yoai_aec3.dll.lib import library, .pdb if present)
    Linux/Android  libyoai_aec3.so
    macOS          libyoai_aec3.dylib
and yoai_aec3.h is copied to --header-dir (default: ../src/voice/aec).

Examples:
    python build_aec3_bridge.py                       # release, host OS and CPU
    python build_aec3_bridge.py --debug
    python build_aec3_bridge.py --target-os android   # Linux/WSL2 host only, arm64 by default
    python build_aec3_bridge.py --target-os ohos --ohos-sdk ~/ohos-sdk   # EXPERIMENTAL, Linux/WSL2 host, arm64
    python build_aec3_bridge.py --no-header           # do not touch the yoai source tree
    python build_aec3_bridge.py --dry-run             # print commands only
    python build_aec3_bridge.py --unpatch

Needs WebRTC fetched and synced (fetch_webrtc.py) and the same host/target rules as
build_aec3.py: Android only on Linux (WSL2 on Windows), iOS is not supported here.
"""
import argparse
import shutil
import sys
from pathlib import Path

import build_aec3 as base

HERE = Path(__file__).resolve().parent
TARGET = "yoai_aec3"
BRIDGE_IN_SRC = "yoai_aec3_bridge"  # where the sources are copied inside the WebRTC src dir
HEADER = "yoai_aec3.h"

# What the bridge uses of WebRTC (see aec3_bridge/yoai_aec3.cc)
DEPS = [
    "//api/audio:aec3_factory",
    "//api/audio:audio_processing",
    "//api/environment:environment_factory",
    "//modules/audio_processing:audio_buffer",
]


def artifact_names(target_os):
    """(main library, optional extras) as GN names them in the output directory."""
    if target_os == "win":
        return "yoai_aec3.dll", ["yoai_aec3.dll.lib", "yoai_aec3.dll.pdb"]
    if target_os == "mac":
        return "libyoai_aec3.dylib", []
    return "libyoai_aec3.so", []


def bridge_files(bridge_dir: Path):
    return sorted(p for p in bridge_dir.iterdir() if p.suffix in (".cc", ".h"))


def stage_bridge(bridge_dir: Path, src: Path, dry_run):
    dest = src / BRIDGE_IN_SRC
    log_files = ", ".join(p.name for p in bridge_files(bridge_dir))
    base.log(f"Copying {log_files} -> {dest}")
    if dry_run:
        return
    shutil.rmtree(dest, ignore_errors=True)
    dest.mkdir(parents=True)
    for f in bridge_files(bridge_dir):
        shutil.copy2(f, dest / f.name)


def cleanup(src: Path):
    base.unpatch_build_gn(src)
    dest = src / BRIDGE_IN_SRC
    if dest.exists():
        shutil.rmtree(dest, ignore_errors=True)
        print(f"Removed {dest}")


def gn_block(bridge_dir: Path):
    sources = [f"{BRIDGE_IN_SRC}/{p.name}" for p in bridge_files(bridge_dir)]
    return (
        [f'shared_library("{TARGET}") {{', "  testonly = false", "  sources = ["]
        + [f'    "{s}",' for s in sources]
        + ["  ]", '  defines = [ "YOAI_AEC3_BUILDING" ]', "  deps = ["]
        + [f'    "{d}",' for d in DEPS]
        + ["  ]", "}"]
    )


# OpenHarmony is Linux with musl. GN has no such target_os, so it is built as target_os="linux"
# through a small generated toolchain that adds the OpenHarmony triple and sysroot.
OHOS_TRIPLES = {"arm64": "aarch64-linux-ohos", "arm": "arm-linux-ohos", "x64": "x86_64-linux-ohos"}


def write_ohos_toolchain(src: Path, sysroot: Path, cpu, dry_run):
    """extra_cflags and friends are parameters of clang_toolchain(), not GN args, hence a toolchain file."""
    flags = f"--target={OHOS_TRIPLES[cpu]} --sysroot={sysroot.as_posix()}"
    text = (
        "# Generated by build_aec3_bridge.py\n"
        'import("//build/toolchain/gcc_toolchain.gni")\n\n'
        f'clang_toolchain("{cpu}") {{\n'
        "  toolchain_args = {\n"
        f'    current_cpu = "{cpu}"\n'
        '    current_os = "linux"\n'
        "  }\n"
        f'  extra_cppflags = "{flags}"\n'
        f'  extra_ldflags = "{flags}"\n'
        "}\n"
    )
    dest = src / BRIDGE_IN_SRC / "ohos"
    base.log(f"Writing the OpenHarmony toolchain ({OHOS_TRIPLES[cpu]}) to {dest / 'BUILD.gn'}")
    print(text)
    if not dry_run:
        dest.mkdir(parents=True, exist_ok=True)
        (dest / "BUILD.gn").write_text(text, encoding="utf-8")


def find_output(out_abs: Path, name):
    # Android links into lib.unstripped/ and puts a stripped copy in the output root
    for d in (out_abs, out_abs / "lib.unstripped"):
        if (d / name).exists():
            return d / name
    return None


def main():
    p = argparse.ArgumentParser(description="Build yoai_aec3, a C-ABI shared library over WebRTC AEC3")
    p.add_argument("-s", "--src-dir", default=str(HERE / "webrtc" / "src"), help="WebRTC src directory (default: webrtc/src next to this script)")
    p.add_argument("--depot-tools", default=None, help="depot_tools directory (default: <src>/../../depot_tools if it exists, else PATH)")
    p.add_argument("--out-dir", default="out/aec3_bridge", help="GN output dir, relative to --src-dir (default: out/aec3_bridge)")
    p.add_argument("--bridge-dir", default=str(HERE / "aec3_bridge"), help="the bridge sources (default: aec3_bridge next to this script)")
    p.add_argument("-o", "--output-dir", default=None, help="where the library goes (default: dist/yoai_aec3/<os>-<cpu> next to this script)")
    p.add_argument("--header-dir", default=str(HERE.parent / "src" / "voice" / "aec"), help="where yoai_aec3.h is copied (default: ../src/voice/aec)")
    p.add_argument("--no-header", action="store_true", help="do not copy the header")

    g = p.add_argument_group("GN configuration")
    g.add_argument("--debug", action="store_true", help="debug build (default: release)")
    g.add_argument("--target-os", default=None, help="win, mac, linux, android or ohos (experimental); allowed values depend on the host OS (default: host OS)")
    g.add_argument("--target-cpu", default=None, help="x64, x86, arm, arm64 (default: arm64 for android and ohos, otherwise the host CPU)")
    g.add_argument("--ohos-sdk", default=None, help="for --target-os ohos: the OpenHarmony SDK (a Linux build of it) -- the directory that contains native/")
    g.add_argument("--symbol-level", type=int, default=None, help="GN symbol_level (default: 0 release, 2 debug)")
    g.add_argument("--gn-arg", action="append", metavar="KEY=VALUE", help="extra GN arg, repeatable (overrides defaults)")

    p.add_argument("-j", "--jobs", type=int, default=None, help="ninja parallel jobs (default: ninja decides)")
    p.add_argument("--clean", action="store_true", help="delete the output dir before generating")
    p.add_argument("--keep-patch", action="store_true", help="keep the copied sources and the BUILD.gn block after the build")
    p.add_argument("--unpatch", action="store_true", help="remove what this script added to the WebRTC src dir, then exit")
    p.add_argument("--dry-run", action="store_true", help="print commands without executing them")
    p.set_defaults(custom_libcxx=False, clang="auto")  # build_aec3.build_gn_args reads these
    a = p.parse_args()

    host_os = {"win32": "win", "darwin": "mac"}.get(sys.platform, "linux")
    ohos = a.target_os == "ohos"
    if a.target_os is None:
        a.target_os = host_os
    elif a.target_os == "ios":
        p.error("iOS is not supported by the bridge: a shared library cannot be shipped next to an iOS app.")
    elif ohos:
        if host_os != "linux":
            p.error("'--target-os ohos' needs a Linux host (WSL2 on Windows): GN builds Linux targets only there.")
        if not a.ohos_sdk:
            p.error("'--target-os ohos' needs --ohos-sdk <OpenHarmony SDK, the Linux build>.")
    elif a.target_os not in base.HOST_TARGETS[host_os]:
        p.error(
            f"'--target-os {a.target_os}' cannot be built on a {host_os} host. "
            f"Allowed on this host: {', '.join(t for t in base.HOST_TARGETS[host_os] if t != 'ios')}. "
            "(Android needs Linux, e.g. WSL2 on Windows.)"
        )
    if a.target_cpu is None:
        a.target_cpu = "arm64" if ohos else base.default_cpu(a.target_os)
    if ohos and a.target_cpu not in OHOS_TRIPLES:
        p.error(f"'--target-cpu {a.target_cpu}' is not available for ohos; use one of {', '.join(OHOS_TRIPLES)}.")

    src = Path(a.src_dir).expanduser().resolve()
    if not (src / "BUILD.gn").exists() or not (src / ".gn").exists():
        sys.exit(f"{src} does not look like a WebRTC src directory (BUILD.gn / .gn missing).")

    if a.unpatch:
        cleanup(src)
        return

    bridge_dir = Path(a.bridge_dir).expanduser().resolve()
    if not (bridge_dir / "yoai_aec3.cc").exists() or not (bridge_dir / HEADER).exists():
        sys.exit(f"{bridge_dir} must contain yoai_aec3.cc and {HEADER}.")

    label_os = "ohos" if ohos else a.target_os  # what the output directory is called
    sysroot = None
    if ohos:
        sdk = Path(a.ohos_sdk).expanduser().resolve()
        sysroot = next((c for c in (sdk / "native" / "sysroot", sdk / "sysroot") if c.is_dir()), None)
        if not sysroot:
            sys.exit(f"No native/sysroot under {sdk}. --ohos-sdk is the OpenHarmony SDK directory that contains native/.")
        if " " in str(sysroot):
            sys.exit(f"The SDK path must not contain spaces (it goes into compiler flags): {sysroot}")
        a.target_os = "linux"  # what GN calls it
        print("[!] ohos is experimental: nothing upstream builds WebRTC for OpenHarmony, so expect to meet musl", flush=True)
        print("    incompatibilities in rtc_base / system_wrappers. Paste the first compile error if one appears.", flush=True)

    if not (src / "build").is_dir():
        print("[!] src/build is missing. Did 'gclient sync' finish? GN may fail.", flush=True)

    env = base.make_env(src, a.depot_tools)
    out_rel = a.out_dir.replace("\\", "/")
    out_abs = src / out_rel

    if a.clean and out_abs.exists():
        base.log(f"Removing {out_abs}")
        if not a.dry_run:
            shutil.rmtree(out_abs)

    # 1. Sources and the GN target must be in place before `gn gen`
    stage_bridge(bridge_dir, src, a.dry_run)
    base.append_block(src, gn_block(bridge_dir), a.dry_run)
    if ohos:
        write_ohos_toolchain(src, sysroot, a.target_cpu, a.dry_run)
        # Ahead of the user's own --gn-arg, so those still win. use_sysroot=false: do not use
        # Chromium's Debian/glibc sysroot; use_custom_libcxx: Chromium's libc++ rather than the SDK's.
        a.gn_arg = [
            f'custom_toolchain="//{BRIDGE_IN_SRC}/ohos:{a.target_cpu}"',
            "is_clang=true",
            "use_sysroot=false",
            "use_custom_libcxx=true",
        ] + (a.gn_arg or [])

    # 2. gn gen
    base.log("gn gen")
    gn_args = base.build_gn_args(a)
    print(f"GN args: {gn_args}")
    base.run([base.resolve("gn", env), "gen", out_rel, f"--args={gn_args}"], cwd=src, env=env, dry_run=a.dry_run)

    # 3. ninja
    base.log(f"ninja {TARGET}")
    cmd = [base.resolve("ninja", env), "-C", out_rel]
    if a.jobs:
        cmd += ["-j", str(a.jobs)]
    base.run(cmd + [TARGET], cwd=src, env=env, dry_run=a.dry_run)

    if a.dry_run:
        base.log("Dry run finished")
        return

    # 4. Locate and copy the results
    main_name, extra_names = artifact_names(a.target_os)
    lib = find_output(out_abs, main_name)
    if not lib:
        sys.exit(f"Build finished but {main_name} was not found under {out_abs}. "
                 "The BUILD.gn block and the copied sources were left in place for inspection (--unpatch removes them).")

    dest = Path(a.output_dir).expanduser().resolve() if a.output_dir else HERE / "dist" / "yoai_aec3" / f"{label_os}-{a.target_cpu}"
    dest.mkdir(parents=True, exist_ok=True)
    copied = [lib]
    for name in extra_names:
        extra = find_output(out_abs, name)
        if extra:
            copied.append(extra)
    for f in copied:
        shutil.copy2(f, dest / f.name)
        print(f"Copied {f.name} ({f.stat().st_size / 1024:.0f} KiB) -> {dest}")

    if not a.no_header:
        header_dir = Path(a.header_dir).expanduser().resolve()
        if header_dir.is_dir():
            shutil.copy2(bridge_dir / HEADER, header_dir / HEADER)
            print(f"Copied {HEADER} -> {header_dir}")
        else:
            print(f"[!] {header_dir} does not exist, header not copied (use --header-dir).", flush=True)

    # 5. The WebRTC checkout was only borrowed for this build; leave it clean
    if not a.keep_patch:
        base.log("Removing the temporary target and sources from the WebRTC src dir")
        cleanup(src)

    base.log("Done")
    print(f"Library: {dest / lib.name}")
    if a.target_os == "win":
        print("Check that it needs nothing but system DLLs (x64 Native Tools prompt):")
        print(f"  dumpbin /dependents {dest / lib.name}")
        print("and that the C API is exported:")
        print(f"  dumpbin /exports {dest / lib.name}")
    else:
        print("Check that it needs nothing but system libraries:")
        print(f"  readelf -d {dest / lib.name} | grep NEEDED")


if __name__ == "__main__":
    main()
