"""Generate the app's palette table from design/palettes.json.

    python design/make-arkts-palettes.py

Writes examples/harmony/entry/src/main/ets/core/Palettes.ets. Run it whenever
palettes.json changes; do not hand-edit the generated file.

palettes.json names its colors the way the design system does. The app names
them the way color.json does, and every use site is a `$r('app.color.NAME')`
that becomes `this.theme.NAME`, so the mapping is applied once -- in
palette_tokens.py, which every host's generator reads -- rather than at 76 call
sites.
"""
import pathlib

from palette_tokens import FIELDS, ORDER, family_of, load

ROOT = pathlib.Path(__file__).resolve().parent.parent
DST = ROOT / "examples/harmony/entry/src/main/ets/core/Palettes.ets"

# design name -> app token name. The nine tokens the design added in round 10
# already use the app's names and need no entry here.
RENAME = {
    "surface-page": "bg_page",
    "surface-card": "bg_surface",
    "surface-inverse": "surface_inverse",
    "text-primary": "text_primary",
    "text-tertiary": "text_tertiary",
    "border": "border",
    "accent": "brand",
    "accent-soft": "accent_soft",
    "muted-on-inverse": "muted_on_inverse",
    "accent-on-inverse": "accent_on_inverse",
}

# Order of the fields on the generated interface, so the file reads in groups.
FIELDS = [
    "bg_page", "bg_surface", "bg_bubble", "bg_overlay", "surface_inverse",
    "text_primary", "text_secondary", "text_tertiary", "text_disabled",
    "brand", "on_brand", "accent_soft", "muted_on_inverse", "accent_on_inverse",
    "border", "divider", "scrim",
    "danger", "success",
]

# The six palettes are three families of two. The app exposes them as two
# independent controls -- light/dark/system, which already exists, and the
# family below -- so the picker offers three rows, not six, and the mode
# control decides which member of the chosen family is in force.
#
# The picker's label for each family is a STRING RESOURCE, not text built here:
# it pairs the design's own name with a temperature word, and how that pair
# reads is a per-language decision. The English name alone would not be enough
# ("Amber" says nothing to someone who has not seen the palette) and a
# hardcoded Chinese half would not follow the language picker.
FAMILY_LABEL = {
    "amber": "settings_palette_amber",
    "arctic": "settings_palette_arctic",
    "quiet": "settings_palette_quiet",
}




def main() -> None:
    doc, rows, families = load()
    themes = doc["themes"]

    out = ['/**', ' * Generated by design/make-arkts-palettes.py -- do not edit.', ' *',
           f' * Source: {doc["source"]}', ' *',
           ' * Every field is a token name from color.json, so a use site that was',
           " * $r('app.color.X') becomes theme.X and nothing else has to change.",
           ' *',
           ' * start_window_background is deliberately absent: the splash background is',
           ' * read before the app runs, so it cannot follow a choice made inside the',
           ' * app and stays a base/dark resource in color.json.',
           ' */', '', 'export interface Palette {', '  key: string;',
           "  /**",
           "   * The design's own name for this palette, e.g. \"Daylight Arctic\".",
           "   *",
           "   * NOT for display: it is a plain string in one language. Anything the",
           "   * user reads comes from Family.label, which is a string resource. This is",
           "   * here for logs and for talking about a palette in the source.",
           "   */",
           '  label: string;',
           '  /** Family this palette belongs to; the two members differ only in mode. */',
           '  family: string;', "  /** 'light' or 'dark' -- also pushed to setColorMode. */",
           '  mode: string;', '  /** Three colors that stand for the palette in the picker chip. */',
           '  swatches: string[];', '  /** Per-state colors for the record screens. */',
           '  state_ramp: string[];']
    for f in FIELDS:
        out.append(f"  {f}: string;")
    out.append("}")
    out.append("")

    order = ORDER

    out.append("export const PALETTES: Palette[] = [")
    for key in order:
        t = themes[key]
        c = rows[key]
        # chip swatches: page, brand, inverse -- ground, accent, and the dark card
        sw = [c["bg_page"], c["brand"], c["surface_inverse"]]
        out.append("  {")
        out.append(f"    key: '{key}',")
        out.append(f"    label: '{t['label']}',")
        out.append(f"    family: '{family_of(key)}',")
        out.append(f"    mode: '{t['mode']}',")
        out.append(f"    swatches: [{', '.join(repr(s).replace(chr(34), chr(39)) for s in sw)}],")
        ramp = ", ".join(f"'{v}'" for v in t["state-ramp"])
        out.append(f"    state_ramp: [{ramp}],")
        for f in FIELDS:
            out.append(f"    {f}: '{c[f]}',")
        out.append("  },")
    out.append("];")
    out.append("")
    out.append(f"export const DEFAULT_PALETTE: string = '{doc['default']}';")
    out.append("")
    out.append("/**")
    out.append(" * The palette with this key, or the default when the key is unknown.")
    out.append(" *")
    out.append(" * The fallback is a second pass rather than a recursive call: these keys")
    out.append(" * come out of persistent storage, and a table that no longer contains its")
    out.append(" * own default should degrade, not overflow the stack.")
    out.append(" */")
    out.append("export function paletteFor(key: string): Palette {")
    out.append("  for (const p of PALETTES) {")
    out.append("    if (p.key === key) {")
    out.append("      return p;")
    out.append("    }")
    out.append("  }")
    out.append("  for (const p of PALETTES) {")
    out.append("    if (p.key === DEFAULT_PALETTE) {")
    out.append("      return p;")
    out.append("    }")
    out.append("  }")
    out.append("  return PALETTES[0];")
    out.append("}")
    out.append("")
    out.append("/** A color family: one light palette and one dark one. */")
    out.append("export interface Family {")
    out.append("  key: string;")
    out.append("  /** Localized picker label, e.g. \"Amber - warm\". */")
    out.append("  label: Resource;")
    out.append("}")
    out.append("")
    out.append("export const FAMILIES: Family[] = [")
    for f in ("amber", "arctic", "quiet"):
        out.append(f"  {{ key: '{f}', label: $r('app.string.{FAMILY_LABEL[f]}') }},")
    out.append("];")
    out.append("")
    out.append(f"export const DEFAULT_FAMILY: string = '{family_of(doc['default'])}';")
    out.append("")
    out.append("/**")
    out.append(" * The family with this key, or the default when the key is unknown.")
    out.append(" *")
    out.append(" * Exists so a summary elsewhere can name the chosen family in the user's")
    out.append(" * language: Palette.label is the design's own English name and is not a")
    out.append(" * string resource, so it must not be shown to anyone.")
    out.append(" */")
    out.append("export function familyFor(key: string): Family {")
    out.append("  for (const f of FAMILIES) {")
    out.append("    if (f.key === key) {")
    out.append("      return f;")
    out.append("    }")
    out.append("  }")
    out.append("  for (const f of FAMILIES) {")
    out.append("    if (f.key === DEFAULT_FAMILY) {")
    out.append("      return f;")
    out.append("    }")
    out.append("  }")
    out.append("  return FAMILIES[0];")
    out.append("}")
    out.append("")
    out.append("/**")
    out.append(" * The palette in force: the requested family's light or dark member.")
    out.append(" *")
    out.append(" * Family and mode are separate controls, so this is where they meet. An")
    out.append(" * unknown family falls back to the default rather than throwing -- the")
    out.append(" * value comes out of persistent storage and can outlive a rename -- and")
    out.append(" * the fallback is a second pass, not recursion, so a table missing its")
    out.append(" * own default degrades instead of overflowing the stack.")
    out.append(" */")
    out.append("export function resolvePalette(family: string, dark: boolean): Palette {")
    out.append("  const want: string = dark ? 'dark' : 'light';")
    out.append("  for (const p of PALETTES) {")
    out.append("    if (p.family === family && p.mode === want) {")
    out.append("      return p;")
    out.append("    }")
    out.append("  }")
    out.append("  for (const p of PALETTES) {")
    out.append("    if (p.family === DEFAULT_FAMILY && p.mode === want) {")
    out.append("      return p;")
    out.append("    }")
    out.append("  }")
    out.append("  return PALETTES[0];")
    out.append("}")
    out.append("")

    DST.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)}")
    print(f"  {len(order)} palettes, {len(FIELDS)} color fields each")
    for f, members in sorted(families.items()):
        print(f"  family {f:7} light={members['light']:16} dark={members['dark']}")


if __name__ == "__main__":
    main()
