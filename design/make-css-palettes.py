"""Generate the desktop client's palette stylesheet from design/palettes.json.

    python design/make-css-palettes.py

Writes desktop/src/renderer/src/palettes.css. Run it whenever palettes.json
changes; do not hand-edit the generated file.

The sibling of make-arkts-palettes.py, against the same source and with the same
invariant checks, emitting what a browser engine reads instead of what ArkTS
does. Two generators rather than one shared intermediate because the two hosts
disagree about almost everything except the hex values: ArkTS wants a typed
table it can index, CSS wants custom properties a cascade can override, and the
one thing worth keeping identical -- the colors -- is identical either way.

Token names are the app's, not the design system's, so the rename table below is
the same one the ArkTS generator applies. The CSS spelling swaps underscores for
dashes and takes a `--bc-` prefix, which is mechanical: bg_page is --bc-bg-page.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "design/palettes.json"
DST = ROOT / "desktop/src/renderer/src/palettes.css"

# design name -> app token name. Must agree with make-arkts-palettes.py: a token
# that means bg_page on the phone and something else on the desktop is the one
# failure a generated file is supposed to make impossible.
RENAME = {
    "surface-page": "bg_page",
    "surface-card": "bg_surface",
    "surface-inverse": "surface_inverse",
    "text-primary": "text_primary",
    "text-tertiary": "text_tertiary",
    "border": "border",
    "accent": "brand",
    "accent-soft": "accent_soft",
    "muted-on-inverse": "muted_on_inverse",
    "accent-on-inverse": "accent_on_inverse",
}

FIELDS = [
    "bg_page", "bg_surface", "bg_bubble", "bg_overlay", "surface_inverse",
    "text_primary", "text_secondary", "text_tertiary", "text_disabled",
    "brand", "on_brand", "accent_soft", "muted_on_inverse", "accent_on_inverse",
    "border", "divider", "scrim",
    "danger", "success",
]

FAMILIES = ("amber", "arctic", "quiet")


def family_of(key: str) -> str:
    for f in FAMILIES:
        if f in key:
            return f
    if key in ("quiet-day", "quiet-night"):
        return "quiet"
    raise SystemExit(f"cannot place {key!r} in a family")


def var_name(field: str) -> str:
    return "--bc-" + field.replace("_", "-")


def rgba(value: str) -> str:
    """Rewrite #AARRGGBB to #RRGGBBAA, which is what CSS reads.

    palettes.json carries four of these -- divider, scrim and their dark
    counterparts -- in the ARGB order ArkTS takes. CSS's 8-digit hex puts alpha
    LAST, so passing one straight through would render the scrim as a nearly
    opaque grey-blue instead of a 42% black: readable enough to ship and wrong.
    """
    if len(value) == 9 and value.startswith("#"):
        return "#" + value[3:] + value[1:3]
    return value


def block(selector: str, colors: dict, ramp: list, indent: str = "  ") -> list:
    out = [f"{selector} {{"]
    for f in FIELDS:
        out.append(f"{indent}{var_name(f)}: {rgba(colors[f])};")
    for i, c in enumerate(ramp, start=1):
        out.append(f"{indent}--bc-state-{i}: {rgba(c)};")
    out.append("}")
    return out


def main() -> None:
    doc = json.load(open(SRC, encoding="utf-8"))
    themes = doc["themes"]

    rows = {}
    for key, t in themes.items():
        colors = {}
        for name, value in t.items():
            if name in ("label", "labelZh", "mode", "note", "state-ramp"):
                continue
            colors[RENAME.get(name, name)] = value
        missing = [f for f in FIELDS if f not in colors]
        if missing:
            raise SystemExit(f"{key}: palettes.json has no {missing}")
        extra = [c for c in colors if c not in FIELDS]
        if extra:
            raise SystemExit(f"{key}: unmapped colors {extra}")
        rows[key] = colors

    members = {}
    for key, t in themes.items():
        members.setdefault(family_of(key), {})[t["mode"]] = key
    for f, pair in members.items():
        if set(pair) != {"light", "dark"}:
            raise SystemExit(f"family {f} is not a light/dark pair: {pair}")

    default_key = doc["default"]
    if default_key not in themes:
        raise SystemExit(f"default palette {default_key!r} is not in the table")
    default_family = family_of(default_key)

    out = [
        "/*",
        " * Generated by design/make-css-palettes.py -- do not edit.",
        " *",
        f" * Source: {doc['source']}",
        " *",
        " * Two attributes on <html> select a palette: data-family is the user's",
        " * choice of three, data-mode is light or dark ALREADY RESOLVED -- 'system'",
        " * is answered before it reaches the DOM, because a stylesheet cannot ask",
        " * the app what the OS said and prefers-color-scheme would then compete",
        " * with an explicit choice.",
        " *",
        f" * The bare :root block is {default_key}, so a document rendered before the",
        " * attributes are set is the default palette rather than an unstyled flash.",
        " */",
        "",
    ]
    out += block(":root", rows[default_key], themes[default_key]["state-ramp"])
    out.append("")

    order = ["daylight-amber", "daylight-arctic", "quiet-day",
             "midnight-amber", "midnight-arctic", "quiet-night"]
    if sorted(order) != sorted(themes):
        raise SystemExit("palette set changed; update `order`")

    for key in order:
        t = themes[key]
        selector = f':root[data-family="{family_of(key)}"][data-mode="{t["mode"]}"]'
        out.append(f"/* {t['label']} */")
        out += block(selector, rows[key], t["state-ramp"])
        out.append("")

    out.append("/*")
    out.append(" * Picker swatches: the three colors that stand for a palette -- page,")
    out.append(" * accent, and the dark card -- the same three the ArkTS table carries.")
    out.append(" *")
    out.append(" * Separate from the blocks above because they are needed OUTSIDE the")
    out.append(" * cascade that selects a palette: the settings screen draws a chip for")
    out.append(" * every family while exactly one of them is in force. Keyed by")
    out.append(" * family-mode rather than by palette key, so a caller needs only the two")
    out.append(" * values it already has and never a list of the six names.")
    out.append(" */")
    for key in order:
        t = themes[key]
        c = rows[key]
        sw = [c["bg_page"], c["brand"], c["surface_inverse"]]
        selector = f'[data-swatch="{family_of(key)}-{t["mode"]}"]'
        out.append(
            selector
            + " { "
            + " ".join(f"--bc-sw-{i}: {v};" for i, v in enumerate(sw, start=1))
            + " }"
        )
    out.append("")

    out.append("/*")
    out.append(" * The scrollbars and form controls the engine draws for itself. Without")
    out.append(" * this a dark palette still gets a light scrollbar, which is the one part")
    out.append(" * of the window the app does not paint.")
    out.append(" */")
    out.append(':root[data-mode="light"] { color-scheme: light; }')
    out.append(':root[data-mode="dark"] { color-scheme: dark; }')
    out.append("")

    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)}")
    print(f"  {len(order)} palettes, {len(FIELDS)} color fields each")
    print(f"  default {default_key} (family {default_family})")


if __name__ == "__main__":
    main()
