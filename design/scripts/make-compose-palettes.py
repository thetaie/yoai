"""Generate the Android app's palette table from design/palettes.json.

    python design/scripts/make-compose-palettes.py

Writes examples/android/app/src/main/kotlin/com/yoai/bodyclock/ui/Palettes.kt. Run it
whenever palettes.json changes; do not hand-edit the generated file.

The third sibling, after make-arkts-palettes.py and make-css-palettes.py, over
the same source and the same invariants in palette_tokens.py. What differs is
only the output: Compose wants a data class of `Color` values, not a typed ArkTS
record and not custom properties.

Two mechanical spellings, both of them decided here and nowhere else:

  * Token names become camelCase, because a Kotlin property named `bg_page`
    would be the one lint every reader trips over. The mapping is exactly
    `bg_page` -> `bgPage`, so the design token is still recoverable by eye.
  * Colors become `Color(0xAARRGGBB)`. palettes.json already carries its four
    translucent tokens -- divider, scrim and their dark counterparts -- in that
    same ARGB order, so unlike the CSS generator this one has no channel
    reordering to do; the six-digit values just gain an opaque alpha.

**Material You is deliberately not used.** Compose's `dynamicColorScheme` reads
the wallpaper, which is a different design than this one and cannot be one of
the six. The bench screen may follow the device; the app does not.
"""
import pathlib

from palette_tokens import FAMILIES, FIELDS, ORDER, family_of, load

ROOT = pathlib.Path(__file__).resolve().parents[2]
DST = ROOT / "examples/android/app/src/main/kotlin/com/yoai/bodyclock/ui/Palettes.kt"

# The picker's label for each family is a STRING RESOURCE, not text built here:
# it pairs the design's own name with a temperature word, and how that pair
# reads is a per-language decision. Same resource names as the ArkTS table, so
# the two apps' settings screens say the same thing.
FAMILY_LABEL = {
    "amber": "settings_palette_amber",
    "arctic": "settings_palette_arctic",
    "quiet": "settings_palette_quiet",
}


def prop(field: str) -> str:
    """bg_page -> bgPage."""
    head, *rest = field.split("_")
    return head + "".join(w.capitalize() for w in rest)


def color(value: str) -> str:
    """#RRGGBB or #AARRGGBB -> Color(0xAARRGGBB)."""
    v = value.lstrip("#")
    if len(v) == 6:
        v = "FF" + v
    if len(v) != 8:
        raise SystemExit(f"cannot read {value!r} as a color")
    return f"Color(0x{v.upper()})"


def main() -> None:
    doc, rows, families = load()
    themes = doc["themes"]

    default_key = doc["default"]
    if default_key not in themes:
        raise SystemExit(f"default palette {default_key!r} is not in the table")
    default_family = family_of(default_key)

    out = [
        "package com.yoai.bodyclock.ui",
        "",
        "import androidx.compose.runtime.Immutable",
        "import androidx.compose.ui.graphics.Color",
        "import com.yoai.bodyclock.R",
        "",
        "// Generated by design/scripts/make-compose-palettes.py -- do not edit.",
        "//",
        f"// Source: {doc['source']}",
        "//",
        "// Token names are the design's, camelCased: bg_page is bgPage. The four",
        "// translucent ones -- divider and scrim, light and dark -- carry a real alpha",
        "// and are meant to be drawn OVER something; treating one as opaque is the",
        "// mistake this comment exists to prevent.",
        "",
        "/**",
        " * One of the six palettes.",
        " *",
        " * Immutable so Compose can skip recomposing everything that merely holds one:",
        " * the palette is passed down through most of the tree and changes only when",
        " * the user picks a different family or the system flips to dark.",
        " */",
        "@Immutable",
        "data class Palette(",
        "    val key: String,",
        "    /**",
        "     * The design's own name, e.g. \"Daylight Arctic\".",
        "     *",
        "     * NOT for display -- it is a plain string in one language. Anything the",
        "     * user reads comes from [Family.label], which is a string resource.",
        "     */",
        "    val label: String,",
        "    /** Family this palette belongs to; the two members differ only in mode. */",
        "    val family: String,",
        "    val dark: Boolean,",
        "    /** Three colors that stand for the palette in the picker chip. */",
        "    val swatches: List<Color>,",
        "    /**",
        "     * Per-state colors for the record screens, in state order.",
        "     *",
        "     * Shorter than the nine states on purpose: it is a ramp to cycle, not a",
        "     * color per state. Index it with `stateRamp[i % stateRamp.size]`.",
        "     */",
        "    val stateRamp: List<Color>,",
    ]
    for f in FIELDS:
        out.append(f"    val {prop(f)}: Color,")
    out.append(")")
    out.append("")

    out.append("val PALETTES: List<Palette> = listOf(")
    for key in ORDER:
        t = themes[key]
        c = rows[key]
        # Chip swatches: page, brand, inverse -- ground, accent, and the dark card.
        sw = [c["bg_page"], c["brand"], c["surface_inverse"]]
        out.append("    Palette(")
        out.append(f'        key = "{key}",')
        out.append(f'        label = "{t["label"]}",')
        out.append(f'        family = "{family_of(key)}",')
        out.append(f"        dark = {'true' if t['mode'] == 'dark' else 'false'},")
        out.append(f"        swatches = listOf({', '.join(color(s) for s in sw)}),")
        out.append(f"        stateRamp = listOf({', '.join(color(v) for v in t['state-ramp'])}),")
        for f in FIELDS:
            out.append(f"        {prop(f)} = {color(c[f])},")
        out.append("    ),")
    out.append(")")
    out.append("")

    out.append(f'const val DEFAULT_PALETTE: String = "{default_key}"')
    out.append(f'const val DEFAULT_FAMILY: String = "{default_family}"')
    out.append("")

    out.append("/** A color family: one light palette and one dark one. */")
    out.append("@Immutable")
    out.append("data class Family(val key: String, @param:androidx.annotation.StringRes val label: Int)")
    out.append("")
    out.append("val FAMILIES: List<Family> = listOf(")
    for f in FAMILIES:
        out.append(f'    Family("{f}", R.string.{FAMILY_LABEL[f]}),')
    out.append(")")
    out.append("")

    out.append("/**")
    out.append(" * The palette in force: the requested family's light or dark member.")
    out.append(" *")
    out.append(" * Family and mode are separate controls, so this is where they meet. An")
    out.append(" * unknown family falls back to the default rather than throwing -- the value")
    out.append(" * comes out of persistent storage and can outlive a rename -- and the")
    out.append(" * fallback is a second lookup, not recursion, so a table that has lost its")
    out.append(" * own default degrades instead of overflowing the stack.")
    out.append(" */")
    out.append("fun resolvePalette(family: String, dark: Boolean): Palette =")
    out.append("    PALETTES.firstOrNull { it.family == family && it.dark == dark }")
    out.append("        ?: PALETTES.firstOrNull { it.family == DEFAULT_FAMILY && it.dark == dark }")
    out.append("        ?: PALETTES.first()")
    out.append("")

    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)}")
    print(f"  {len(ORDER)} palettes, {len(FIELDS)} color fields each")
    print(f"  default {default_key} (family {default_family})")


if __name__ == "__main__":
    main()
